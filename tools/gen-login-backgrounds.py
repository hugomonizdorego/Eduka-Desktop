"""Make the LightDM login backgrounds and the greeter GTK themes.

The backgrounds are the soft gradients the SDDM login screen draws
(usr/share/sddm/themes/edukasaun/Main.qml), one picture per style; every row
has one color, so the PNG files stay a few KB. The themes Edukasaun-Login
(pastel) and Edukasaun-Login-Dark (dark) are the Eduka GTK themes with the
login card of eduka-lightdm-apply's greeter_css(); Eduka-Settings writes the
chosen style and accent over them (~lightdm/.config/gtk-3.0/gtk.css).

  python3 tools/gen-login-backgrounds.py
"""
import importlib.machinery, importlib.util, os, struct, zlib

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'usr', 'share', 'edukasaun-desktop', 'login')
W, H = 1920, 1080
STYLES = {  # top, middle, bottom (Main.qml GradientStop colors)
    'pastel': ('#d6e8f8', '#edf7f2', '#d6efe6'),
    'light': ('#e9f6c9', '#8fcf7a', '#1f6b45'),
    'dark': ('#2f3b39', '#1f2a28', '#121616'),
    'glass': ('#bfe3f5', '#7fb9dc', '#2f6f9a'),
}


def rgb(c):
    return tuple(int(c[i:i + 2], 16) for i in (1, 3, 5))


def mix(a, b, t):
    return tuple(round(x + (y - x) * t) for x, y in zip(a, b))


def png(path, rows):
    raw = b''.join(b'\x00' + bytes(color) * W for color in rows)
    def chunk(kind, data):
        return struct.pack('>I', len(data)) + kind + data + struct.pack('>I', zlib.crc32(kind + data) & 0xffffffff)
    with open(path, 'wb') as f:
        f.write(b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', W, H, 8, 2, 0, 0, 0))
                + chunk(b'IDAT', zlib.compress(raw, 9)) + chunk(b'IEND', b''))


ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
THEMES = {'Edukasaun-Login': ('Eduka-Pastel', 'pastel', '#3fa684', 'Edukasaun login screen (LightDM), light'),
          'Edukasaun-Login-Dark': ('Edukasaun-Dark', 'dark', '#26a69a', 'Edukasaun login screen (LightDM), dark')}


def themes():
    helper = os.path.join(ROOT, 'usr', 'lib', 'edukasaun-desktop', 'eduka-lightdm-apply')
    loader = importlib.machinery.SourceFileLoader('eduka_lightdm_apply', helper)
    spec = importlib.util.spec_from_loader(loader.name, loader); mod = importlib.util.module_from_spec(spec)
    loader.exec_module(mod)
    for name, (base, style, accent, comment) in THEMES.items():
        folder = os.path.join(ROOT, 'usr', 'share', 'themes', name)
        os.makedirs(os.path.join(folder, 'gtk-3.0'), exist_ok=True)
        with open(os.path.join(folder, 'index.theme'), 'w', encoding='utf-8') as f:
            f.write('[Desktop Entry]\nType=X-GNOME-Metatheme\nName=%s\nComment=%s\nEncoding=UTF-8\n\n'
                    '[X-GNOME-Metatheme]\nGtkTheme=%s\nIconTheme=%s\n' % (name, comment, name, 'Papirus-Dark' if style == 'dark' else 'Papirus-Light'))
        css = mod.greeter_css(style, accent).replace('Written by Eduka-Settings → Login & Fingerprint → LightDM; replaced on every change.', 'Eduka-Settings → Login & Fingerprint → LightDM writes the chosen colors over it.')
        with open(os.path.join(folder, 'gtk-3.0', 'gtk.css'), 'w', encoding='utf-8') as f:
            f.write('/* %s: the %s GTK theme with the Edukasaun login card (generated by\n'
                    '   tools/gen-login-backgrounds.py; GPL-3.0-or-later like the theme it uses). */\n'
                    '@import url("../../%s/gtk-3.0/gtk.css");\n\n' % (name, base, base) + css)
        with open(os.path.join(folder, 'README.Edukasaun'), 'w', encoding='utf-8') as f:
            f.write('%s is only for the LightDM greeters (slick-greeter and lightdm-gtk-greeter).\n'
                    'It uses the %s GTK theme (see its folder for the license) and adds the\n'
                    'Edukasaun login card. Generated by tools/gen-login-backgrounds.py.\n' % (name, base))
        print(folder)


# slick-greeter writes white names over the background: its pictures are the
# same gradients mixed with a deep color, so the text stays readable.
SLICK_DEEP = {'pastel': ('#1f6b5a', 0.6), 'light': ('#1f6b45', 0.45), 'dark': ('#000000', 0.0), 'glass': ('#1d4f73', 0.5)}


def small_logo():
    """The logo of slick-greeter (drawn at its own size): 112 px high."""
    from PyQt5.QtGui import QImage
    from PyQt5.QtCore import Qt
    src = os.path.join(ROOT, 'usr', 'share', 'sddm', 'themes', 'edukasaun', 'logo.png')
    img = QImage(src)
    if img.isNull():
        return
    out = os.path.join(OUT, 'logo-small.png')
    img.scaledToHeight(112, Qt.SmoothTransformation).save(out, 'PNG')
    print(out, os.path.getsize(out))


def main():
    themes()
    os.makedirs(OUT, exist_ok=True)
    small_logo()
    for name, (top, mid, bottom) in STYLES.items():
        top, mid, bottom = rgb(top), rgb(mid), rgb(bottom)
        rows = []
        for y in range(H):
            t = y / (H - 1)
            rows.append(mix(top, mid, t * 2) if t < 0.5 else mix(mid, bottom, (t - 0.5) * 2))
        path = os.path.join(OUT, name + '.png')
        png(path, rows)
        print(path, os.path.getsize(path))
        deep, amount = SLICK_DEEP[name]
        path = os.path.join(OUT, 'slick-' + name + '.png')
        png(path, [mix(c, rgb(deep), amount) for c in rows])
        print(path, os.path.getsize(path))


if __name__ == '__main__':
    main()
